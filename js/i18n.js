  /* ──────────────────────────────────────────────────────────────────────────
     Layout helpers
  ────────────────────────────────────────────────────────────────────────── */
  function fixLayout(lang) {
    var isAr = (lang === 'ar');

    /* Footer direction & text alignment */
    document.querySelectorAll('.footer').forEach(function (el) {
      el.style.direction = isAr ? 'rtl' : 'ltr';
    });
    document.querySelectorAll('.footer .col-lg-3, .footer .col-md-6').forEach(function (el) {
      if (isAr) { el.classList.add('text-end'); el.classList.remove('text-start'); }
      else       { el.classList.remove('text-end'); el.classList.add('text-start'); }
    });
    document.querySelectorAll('.footer .btn-link').forEach(function (el) {
      if (isAr) { el.classList.add('text-end'); el.classList.remove('text-start'); }
      else       { el.classList.remove('text-end'); el.classList.add('text-start'); }
    });

    /* Navbar: me-auto (RTL pushes right) ↔ ms-auto (LTR pushes right) */
    document.querySelectorAll('.navbar-nav').forEach(function (el) {
      if (isAr) { el.classList.add('me-auto'); el.classList.remove('ms-auto'); }
      else       { el.classList.remove('me-auto'); el.classList.add('ms-auto'); }
    });

    /* Flip the partner button arrow icon */
    document.querySelectorAll('.btn-partner-arrow').forEach(function (el) {
      el.className = el.className.replace(/fa-arrow-(left|right)/, isAr ? 'fa-arrow-left' : 'fa-arrow-right');
    });
  }

  /* ──────────────────────────────────────────────────────────────────────────
     Core: apply a language
  ────────────────────────────────────────────────────────────────────────── */
  function applyLang(lang) {
    if (lang !== 'ar' && lang !== 'en') lang = 'ar';
    var isAr = (lang === 'ar');
    var html = document.documentElement;

    /* 1. HTML attributes */
    html.lang = lang;
    html.dir  = isAr ? 'rtl' : 'ltr';
    html.setAttribute('data-lang', lang);

    /* 2. Translate text nodes */
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var val = dict[lang][key];
      if (val !== undefined) el.textContent = val;
    });

    /* 3. Translate placeholders */
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-placeholder');
      var val = dict[lang][key];
      if (val !== undefined) el.placeholder = val;
    });

    /* 4. Update the switcher button */
    var btn = document.getElementById('lang-switcher');
    if (btn) btn.textContent = isAr ? 'English' : 'العربية';

    /* 5. Layout adjustments */
    fixLayout(lang);

    /* 6. Persist */
    try { localStorage.setItem('hpc-lang', lang); } catch (e) {}
  }

  /* ──────────────────────────────────────────────────────────────────────────
     Initialise on DOM ready
  ────────────────────────────────────────────────────────────────────────── */
  function init() {
    var saved;
    try { saved = localStorage.getItem('hpc-lang'); } catch (e) {}
    applyLang(saved || 'ar');

    var btn = document.getElementById('lang-switcher');
    if (btn) {
      btn.addEventListener('click', function (e) {
        e.preventDefault();
        var cur;
        try { cur = localStorage.getItem('hpc-lang'); } catch (e) {}
        applyLang(cur === 'en' ? 'ar' : 'en');
      });
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
